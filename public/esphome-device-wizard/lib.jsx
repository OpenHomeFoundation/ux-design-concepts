function Btn({ variant = "filled", tone, block, disabled, onClick, leadingIcon, children, autoFocus }) {
  const cls = ["ha-btn", `ha-btn--${variant}`];
  if (tone) cls.push(`ha-btn--${tone}`);
  if (block) cls.push("ha-btn--block");
  return (
    <button className={cls.join(" ")} disabled={disabled} onClick={onClick} autoFocus={autoFocus}>
      {leadingIcon ? <Icon path={leadingIcon} size={18}></Icon> : null}
      {children}
    </button>
  );
}

// Brand integration icon with graceful fallback to an MDI glyph chip.
function BrandIcon({ domain, size = 40, fallbackPath, tint = "#5a5a5a" }) {
  const [failed, setFailed] = React.useState(false);
  if (failed || !domain) {
    return (
      <div className="icon-chip" style={{ width: size, height: size, background: tint + "22" }}>
        <Icon path={fallbackPath || ICONS.chip} size={Math.round(size * 0.55)} color={tint}></Icon>
      </div>
    );
  }
  return (
    <img
      src={`https://brands.home-assistant.io/${domain}/icon.png`}
      alt=""
      width={size}
      height={size}
      style={{ objectFit: "contain", flex: "none" }}
      onError={() => setFailed(true)}
    />
  );
}

